// After `vite build`: turn the built index.html into the Frappe page www/portal.html.
// Frappe renders it as Jinja, so the session's CSRF token is injected server-side (no token in storage).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, "../../pakistan_tax_consultancy");
const html = readFileSync(resolve(app, "public/frontend/index.html"), "utf8");
const boot = '    <script>window.csrf_token = "{{ csrf_token }}";</script>\n  </head>';
const page = "{# Generated by frontend/scripts/write-portal-page.mjs — edit frontend/index.html instead #}\n" +
  html.replace("</head>", boot);
writeFileSync(resolve(app, "www/portal.html"), page);
console.log("www/portal.html written");
